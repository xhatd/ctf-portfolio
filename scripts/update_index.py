#!/usr/bin/env python3
"""Regenerate README dashboard from per-challenge metadata.json files (stdlib only)."""
import json
import re
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
PLATFORMS = {"tryhackme": "TryHackMe", "hackthebox": "Hack The Box", "picoctf": "picoCTF"}
VALID_STATUSES = {"Completed", "In Progress", "Planned"}


def safe_cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def replace_section(content, name, replacement):
    pattern = rf"(<!-- {name}_START -->).*?(<!-- {name}_END -->)"
    result, count = re.subn(pattern, lambda m: m.group(1) + "\n" + replacement + "\n" + m.group(2), content, flags=re.S)
    if count != 1:
        raise RuntimeError(f"Expected one {name} section in README.md")
    return result


def main():
    entries = []
    for folder, platform in PLATFORMS.items():
        for data_file in sorted((ROOT / folder).glob("*/metadata.json")):
            data = json.loads(data_file.read_text(encoding="utf-8"))
            title = data.get("title", "Untitled")
            status = data.get("status", "Planned")
            if status not in VALID_STATUSES:
                raise ValueError(f"Invalid status in {data_file}: {status}")
            categories = data.get("category", [])
            if isinstance(categories, str):
                categories = [categories]
            if not isinstance(categories, list):
                raise ValueError(f"category must be a list in {data_file}")
            relative = data_file.parent.relative_to(ROOT).as_posix()
            # Folder and file names are generated by the filesystem, never from metadata.
            link = "/".join(quote(part) for part in relative.split("/")) + "/README.md"
            entries.append({"title": title, "platform": platform, "difficulty": data.get("difficulty", "—"),
                            "category": ", ".join(map(str, categories)) or "—", "status": status,
                            "completed": data.get("completed", "") or "—", "link": link})

    entries.sort(key=lambda x: (x["status"] != "Completed", str(x["completed"]), str(x["title"]).lower()), reverse=False)
    completed = sum(e["status"] == "Completed" for e in entries)
    ongoing = sum(e["status"] == "In Progress" for e in entries)
    platforms = len(set(e["platform"] for e in entries))
    stats = f"**Completed:** {completed} · **In progress:** {ongoing} · **Platforms:** {platforms}"
    lines = ["| Challenge | Platform | Difficulty | Category | Status | Completed |", "|---|---|---|---|---|---|"]
    for entry in entries:
        title = safe_cell(entry["title"]).replace("[", "\\[").replace("]", "\\]")
        lines.append("| [{title}]({link}) | {platform} | {difficulty} | {category} | {status} | {completed} |".format(
            title=title, link=entry["link"], **{k: safe_cell(v) for k, v in entry.items() if k not in {"title", "link"}}))
    if not entries:
        lines.append("| _Add your first challenge to get started_ | — | — | — | — | — |")
    readme_file = ROOT / "README.md"
    readme = readme_file.read_text(encoding="utf-8")
    readme = replace_section(readme, "STATS", stats)
    readme = replace_section(readme, "TABLE", "\n".join(lines))
    readme_file.write_text(readme, encoding="utf-8")
    print(f"Updated dashboard: {len(entries)} challenge(s)")


if __name__ == "__main__":
    main()
